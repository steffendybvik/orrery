// Postgres's schema: one baseline, SQLite's schema at step BASELINE written for Postgres, then a step for each of
// SQLite's after it (migrations/sqlite.ts), tracked in `schema_version`. postgres.ts lays down the baseline on an empty
// database and runs the steps it hasn't had. test/schema-parity.test.ts holds the two lists to the same schema.

/** SQLite's step this schema matches (`PRAGMA user_version`). */
export const BASELINE = 23

const KEYS = 'DEFERRABLE INITIALLY IMMEDIATE'
export const SCHEMA = `
    CREATE TABLE projects (
        id text PRIMARY KEY,
        name text NOT NULL,
        key text NOT NULL,
        description text,
        next_number integer NOT NULL DEFAULT 1,
        next_chunk integer NOT NULL DEFAULT 1,
        icon text,
        icon_color text,
        focus_prompt text,
        chunk_prompt text,
        instructions text NOT NULL DEFAULT '[]',
        muted text NOT NULL DEFAULT '[]',
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL
    );
    CREATE TABLE statuses (
        id text PRIMARY KEY,
        name text NOT NULL,
        kind text NOT NULL CHECK (kind IN ('backlog', 'todo', 'started', 'done', 'canceled')),
        color text NOT NULL,
        position double precision NOT NULL
    );
    INSERT INTO statuses (id, name, kind, color, position) VALUES
        ('backlog', 'Backlog', 'backlog', 'slate', 0),
        ('todo', 'Todo', 'todo', 'blue', 1),
        ('in-progress', 'In progress', 'started', 'amber', 2),
        ('in-review', 'In review', 'started', 'violet', 3),
        ('done', 'Done', 'done', 'green', 4),
        ('canceled', 'Canceled', 'canceled', 'slate', 5);
    CREATE TABLE chunks (
        project text NOT NULL REFERENCES projects(id) ON DELETE CASCADE ${KEYS},
        id text NOT NULL,
        title text NOT NULL,
        summary text,
        priority text CHECK (priority IN ('P0', 'P1', 'P2', 'P3')),
        position double precision NOT NULL,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL,
        PRIMARY KEY (project, id)
    );
    CREATE TABLE issues (
        project text NOT NULL REFERENCES projects(id) ON DELETE CASCADE ${KEYS},
        id text NOT NULL,
        title text NOT NULL,
        status text NOT NULL DEFAULT 'backlog' REFERENCES statuses(id) ${KEYS},
        priority text CHECK (priority IN ('P0', 'P1', 'P2', 'P3')),
        assignee text,
        labels text NOT NULL DEFAULT '[]',
        notes text,
        parent text,
        chunk text,
        position double precision NOT NULL,
        schedule integer,
        proposal text CHECK (proposal IN ('pending', 'approved', 'changes', 'rejected')),
        decided_by text,
        decided_at text,
        decision_note text,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL,
        PRIMARY KEY (project, id),
        FOREIGN KEY (project, parent) REFERENCES issues(project, id) ON DELETE CASCADE ${KEYS},
        FOREIGN KEY (project, chunk) REFERENCES chunks(project, id) ${KEYS}
    );
    CREATE INDEX issues_parent ON issues(project, parent);
    CREATE TABLE comments (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        project text NOT NULL,
        issue text NOT NULL,
        body text NOT NULL,
        asks text CHECK (asks IN ('decision', 'feedback')),
        cleared integer NOT NULL DEFAULT 0,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL,
        FOREIGN KEY (project, issue) REFERENCES issues(project, id) ON DELETE CASCADE ${KEYS}
    );
    CREATE INDEX comments_issue ON comments(project, issue);
    CREATE TABLE issue_events (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        project text NOT NULL,
        issue text NOT NULL,
        field text NOT NULL,
        before text,
        after text,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        FOREIGN KEY (project, issue) REFERENCES issues(project, id) ON DELETE CASCADE ${KEYS}
    );
    CREATE INDEX issue_events_issue ON issue_events(project, issue);
    CREATE TABLE issue_sessions (
        project text NOT NULL,
        issue text NOT NULL,
        session text NOT NULL,
        at text NOT NULL,
        PRIMARY KEY (project, issue),
        FOREIGN KEY (project, issue) REFERENCES issues(project, id) ON DELETE CASCADE ON UPDATE CASCADE ${KEYS}
    );
    CREATE TABLE issue_aliases (
        project text NOT NULL,
        alias text NOT NULL,
        issue text NOT NULL,
        PRIMARY KEY (project, alias)
    );
    CREATE TABLE chunk_aliases (
        project text NOT NULL,
        alias text NOT NULL,
        chunk text NOT NULL,
        PRIMARY KEY (project, alias)
    );
    CREATE TABLE docs (
        project text NOT NULL REFERENCES projects(id) ON DELETE CASCADE ${KEYS},
        id text NOT NULL,
        title text NOT NULL,
        body text NOT NULL DEFAULT '',
        position double precision NOT NULL,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL,
        PRIMARY KEY (project, id)
    );
    CREATE TABLE schedules (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        project text NOT NULL REFERENCES projects(id) ON DELETE CASCADE ${KEYS},
        kind text NOT NULL DEFAULT 'issue' CHECK (kind IN ('issue', 'message')),
        title text NOT NULL,
        notes text,
        cron text,
        at text,
        timezone text NOT NULL,
        place text NOT NULL DEFAULT 'todo' REFERENCES statuses(id) ${KEYS},
        chunk text,
        priority text CHECK (priority IN ('P0', 'P1', 'P2', 'P3')),
        labels text NOT NULL DEFAULT '[]',
        ask integer NOT NULL DEFAULT 0,
        skip_open integer NOT NULL DEFAULT 1,
        enabled integer NOT NULL DEFAULT 1,
        next_run text,
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        updated_at text NOT NULL,
        CHECK ((cron IS NULL) != (at IS NULL))
    );
    CREATE INDEX schedules_due ON schedules(enabled, next_run);
    CREATE TABLE schedule_runs (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        schedule integer NOT NULL REFERENCES schedules(id) ON DELETE CASCADE ${KEYS},
        at text NOT NULL,
        outcome text NOT NULL CHECK (outcome IN ('made', 'sent', 'skipped', 'failed')),
        issue text,
        note text
    );
    CREATE INDEX schedule_runs_schedule ON schedule_runs(schedule, id);
    CREATE TABLE signals (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        project text NOT NULL REFERENCES projects(id) ON DELETE CASCADE ${KEYS},
        kind text NOT NULL CHECK (kind IN ('focus', 'comment', 'message')),
        issue text,
        chunk text,
        status text,
        schedule integer,
        note text,
        target text,
        instructions text NOT NULL DEFAULT '[]',
        delivered_to text NOT NULL DEFAULT '[]',
        created_by text NOT NULL,
        owned integer NOT NULL DEFAULT 0,
        created_at text NOT NULL,
        CHECK (kind = 'message' OR (issue IS NULL) != (chunk IS NULL))
    );
    CREATE INDEX signals_project ON signals(project, id);
    CREATE TABLE settings (
        key text PRIMARY KEY,
        value text NOT NULL
    );
`

